#!/usr/bin/env python3
"""Regenerate ``configs/default.yaml`` from the configuration dataclasses.

The file documents every option with its default value. It is generated so that
it cannot drift from the code; ``tests/test_config_file.py`` checks that it is
up to date.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from ssj.collect.qc import QCConfig
from ssj.collect.recorder import RecorderConfig
from ssj.config import to_dict
from ssj.data.augment import AugmentConfig
from ssj.data.build import DatasetConfig
from ssj.models.encoder import ModelConfig
from ssj.runtime.pipeline import PipelineConfig
from ssj.train.adapt import AdaptConfig
from ssj.train.trainer import TrainConfig

HEADER = """\
# silent-speech-jaw: every option with its default value.
#
# Pass a file with only the options you want to change:
#     ssj train --data data/processed --out runs/x -c my.yaml
# or override single options on the command line:
#     ssj train ... -s train.epochs=200 -s model.d_model=160
#
# Sections and the commands that read them:
#     dataset   ssj data build, ssj record (front-end and segmenter)
#     model, train, augment   ssj train
#     adapt     ssj adapt
#     recorder, qc            ssj record
#     pipeline  ssj eval, ssj tune, ssj decode, ssj live
#
# Changing anything under dataset.frontend changes the features and therefore
# the front-end fingerprint: datasets must be rebuilt and models retrained.
#
# Generated by tools/write_default_config.py - do not edit by hand.
"""

SECTIONS = {
    "dataset": DatasetConfig,
    "model": ModelConfig,
    "train": TrainConfig,
    "augment": AugmentConfig,
    "adapt": AdaptConfig,
    "recorder": RecorderConfig,
    "qc": QCConfig,
    "pipeline": PipelineConfig,
}


class _Dumper(yaml.SafeDumper):
    """Block style for sections, flow style for the short lists inside them."""


_Dumper.add_representer(
    list, lambda dumper, data: dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=True)
)


def render() -> str:
    defaults = {name: to_dict(cls()) for name, cls in SECTIONS.items()}
    body = yaml.dump(defaults, Dumper=_Dumper, sort_keys=False, default_flow_style=False, width=100)
    return HEADER + "\n" + body


if __name__ == "__main__":
    path = Path(__file__).resolve().parents[1] / "configs" / "default.yaml"
    path.write_text(render())
    print(f"wrote {path}")
